"""Chat-operated thumbnail jobs; generation is performed by Codex image_gen, not the website."""
import argparse, hashlib, json, re, shutil, struct, zlib
from pathlib import Path
from datetime import datetime, timezone
ROOT = Path(__file__).resolve().parents[2]
BASE = Path(__file__).resolve().parent
JOBS = BASE / 'jobs'
MANIFEST = BASE / 'manifest.json'
PUBLIC = ROOT / 'busan-drop' / 'thumbnail-assets.js'

def read(p, default=None):
    return json.loads(p.read_text(encoding='utf-8-sig')) if p.exists() else default

def write(p, value):
    p.parent.mkdir(parents=True, exist_ok=True)
    temp = p.with_suffix(p.suffix + '.tmp')
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
    temp.replace(p)

def slug(value):
    if not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,63}', value):
        raise ValueError('Product key must contain lowercase letters, numbers and hyphens (max 64).')
    return value

def png_info(path):
    data = path.read_bytes()
    if len(data) > 30 * 1024 * 1024 or data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('Expected generated PNG, at most 30 MB.')
    pos = 8; dims = None; ended = False; image_data = bytearray()
    while pos + 12 <= len(data):
        size = struct.unpack('>I', data[pos:pos+4])[0]
        kind = data[pos+4:pos+8]; payload = data[pos+8:pos+8+size]
        if pos+12+size > len(data): raise ValueError('Truncated PNG')
        crc = struct.unpack('>I', data[pos+8+size:pos+12+size])[0]
        if zlib.crc32(kind+payload) & 0xffffffff != crc: raise ValueError('Invalid PNG checksum')
        if kind == b'IHDR': dims = struct.unpack('>II', payload[:8])
        if kind == b'IDAT': image_data.extend(payload)
        pos += size + 12
        if kind == b'IEND': ended = True; break
    if not ended or not dims or not image_data: raise ValueError('Incomplete PNG')
    if max(dims)>4096 or min(dims)<1024 or abs(dims[0]/dims[1]-1)>.05:
        raise ValueError('Need square PNG with each edge 1024–4096 px (ratio tolerance 5%).')
    return dims, hashlib.sha256(data).hexdigest()

def emit(manifest):
    # Only public asset metadata is shipped. Source paths/prompts/jobs never enter the browser.
    public = {key: {'src': item['src'], 'alt': item['alt']} for key, item in manifest.items()}
    temp = PUBLIC.with_suffix('.js.tmp')
    payload = json.dumps(public, ensure_ascii=False).replace('<', '\\u003c')
    temp.write_text('/* Generated by internal thumbnail pipeline. */\nwindow.BUSAN_THUMBNAILS = '+payload+';\n', encoding='utf-8')
    temp.replace(PUBLIC)

def prepare(args):
    key = slug(args.key); sources = [Path(p).resolve(strict=True) for p in args.source]
    if any(not p.is_file() for p in sources): raise ValueError('Sources must be image files')
    style = read(BASE/'style.json'); angle = style['angles'][int(hashlib.sha256(key.encode()).hexdigest()[:8],16)%len(style['angles'])]
    job_id = key+'-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    folder = JOBS/job_id; folder.mkdir(parents=True)
    prompt = f'''Use case: precise-object-edit / product-mockup.
Edit target: supplied product image(s), same product: {args.name}.
Create a high resolution square thumbnail matching the existing BUSAN DROP NIVEA reference style.
Upscale and clean compression artifacts without inventing product details.
Composition: {style['composition']}. Gently rotate whole product {angle} degrees in-plane; maintain front label readability. Adapt framing to the supplied product shape. Do not invent a new camera viewpoint.
Background: {style['background']}.
Lighting: {style['lighting']}.
Constraints: {style['invariants']}
Avoid: {style['avoid']}
Deliver a square PNG, minimum 1024 pixels per edge. No UI overlays.
'''
    job = {'id':job_id,'key':key,'name':args.name,'sources':[str(p) for p in sources],'style':style['style'],'angle':angle,'prompt':prompt,'status':'prepared'}
    write(folder/'job.json',job);(folder/'prompt.txt').write_text(prompt,encoding='utf-8')
    print(json.dumps({'job':job_id,'prompt_file':str(folder/'prompt.txt'),'sources':job['sources'],'next':'Inspect sources, call built-in image_gen with this prompt and sources, visually review result, then publish --reviewed.'},ensure_ascii=False))

def publish(args):
    if Path(args.job).name != args.job: raise ValueError('Invalid job ID')
    path=JOBS/args.job/'job.json';job=read(path)
    if not job: raise ValueError('Unknown job')
    if not args.reviewed: raise ValueError('Visually inspect packaging, label, crop and identity first; pass --reviewed afterward.')
    result=Path(args.result).resolve(strict=True);dims,digest=png_info(result)
    key=slug(job['key']);dest=ROOT/'busan-drop'/'assets'/'products'/key/(digest[:16]+'.png')
    dest.parent.mkdir(parents=True,exist_ok=True)
    if not dest.exists(): shutil.copyfile(result,dest)
    manifest=read(MANIFEST,{})
    history=manifest.get(key,{}).get('history',[])
    item={'src':dest.relative_to(ROOT/'busan-drop').as_posix(),'alt':job['name']+' 제품 연출 이미지','job':job['id'],'dimensions':dims,'sha256':digest}
    if not history or history[-1]['src']!=item['src']: history.append(item.copy())
    item['history']=history;manifest[key]=item
    write(MANIFEST,manifest);emit(manifest)
    job.update(status='published',result=item['src']);write(path,job)
    print(json.dumps({'published':key,'src':item['src'],'dimensions':dims},ensure_ascii=False))

def rollback(args):
    manifest=read(MANIFEST,{});key=slug(args.key);item=manifest.get(key,{})
    history=item.get('history',[])
    if len(history)<2: raise ValueError('No previous version')
    previous=history[-2].copy();previous['history']=history[:-1];manifest[key]=previous
    write(MANIFEST,manifest);emit(manifest);print('Restored '+previous['src'])

def main():
    parser=argparse.ArgumentParser(description=__doc__);sub=parser.add_subparsers(dest='command',required=True)
    p=sub.add_parser('prepare');p.add_argument('--key',required=True);p.add_argument('--name',required=True);p.add_argument('--source',required=True,nargs='+');p.set_defaults(run=prepare)
    p=sub.add_parser('publish');p.add_argument('--job',required=True);p.add_argument('--result',required=True);p.add_argument('--reviewed',action='store_true');p.set_defaults(run=publish)
    p=sub.add_parser('rollback');p.add_argument('--key',required=True);p.set_defaults(run=rollback)
    p=sub.add_parser('list');p.set_defaults(run=lambda _:print(json.dumps(read(MANIFEST,{}),ensure_ascii=False,indent=2)))
    args=parser.parse_args()
    try: args.run(args)
    except (ValueError,OSError,KeyError) as error: parser.exit(1,str(error)+'\n')
if __name__=='__main__': main()
